begin;

create table public.products (
  id integer generated by default as identity primary key check (id > 0),
  name text not null check (length(trim(name)) between 1 and 200),
  price numeric(12,2) not null check (price >= 0),
  description text not null default '',
  image text not null default 'default.png',
  category text not null default 'Others',
  stock integer not null default 0 check (stock >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  legacy_id bigint unique check (legacy_id > 0),
  name text not null default '' check (length(name) <= 200),
  email text not null,
  role text not null default 'customer' check (role in ('customer','admin')),
  profile_picture text,
  phone text check (length(phone) <= 40),
  gender text check (length(gender) <= 40),
  dob date check (dob >= date '1900-01-01'),
  address text check (length(address) <= 500),
  city text check (length(city) <= 120),
  province text check (length(province) <= 120),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete restrict,
  idempotency_key uuid not null,
  request_items jsonb not null,
  subtotal numeric(12,2) not null check (subtotal >= 0),
  shipping numeric(12,2) not null default 100 check (shipping >= 0),
  total numeric(12,2) not null check (total = subtotal + shipping),
  currency text not null default 'PHP' check (currency = 'PHP'),
  payment_method text not null default 'demo' check (payment_method = 'demo'),
  status text not null default 'placed' check (status in ('placed','cancelled','completed')),
  delivery_name text not null,
  delivery_email text not null,
  delivery_phone text,
  delivery_address text not null,
  delivery_city text,
  delivery_province text,
  created_at timestamptz not null default now(),
  unique (user_id,idempotency_key)
);

create table public.order_items (
  id bigint generated always as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id integer not null references public.products(id) on delete restrict,
  product_name text not null,
  unit_price numeric(12,2) not null check (unit_price >= 0),
  quantity integer not null check (quantity between 1 and 99),
  image text not null,
  unique (order_id,product_id)
);
create index orders_user_created_idx on public.orders(user_id,created_at desc);
create index order_items_order_idx on public.order_items(order_id);
create index products_category_idx on public.products(category);

create function public.set_updated_at() returns trigger
language plpgsql set search_path = '' as $$
begin
  -- Service-side imports can provide an original timestamp; regular writes keep this column unchanged.
  if new.updated_at is not distinct from old.updated_at then new.updated_at = now(); end if;
  return new;
end;
$$;
create trigger products_updated before update on public.products
for each row execute function public.set_updated_at();
create trigger profiles_updated before update on public.profiles
for each row execute function public.set_updated_at();

-- Defense in depth: profile writes cannot change identity or assign an admin role.
create function public.protect_profile_identity() returns trigger
language plpgsql set search_path = '' as $$
begin
  if current_user not in ('postgres','supabase_admin','service_role') and
     (new.id is distinct from old.id or new.legacy_id is distinct from old.legacy_id or
      new.email is distinct from old.email or new.role is distinct from old.role) then
    raise exception 'Profile identity and roles are managed by the server.' using errcode = '42501';
  end if;
  return new;
end;
$$;
create trigger profile_identity_guard before update on public.profiles
for each row execute function public.protect_profile_identity();

create function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles(id,email,name,role)
  values (new.id, coalesce(new.email,''), left(coalesce(new.raw_user_meta_data->>'name',''),200),'customer');
  return new;
end;
$$;
create trigger on_auth_user_created after insert on auth.users
for each row execute function public.handle_new_user();

create function public.sync_profile_email() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  update public.profiles set email = coalesce(new.email,'') where id = new.id;
  return new;
end;
$$;
create trigger on_auth_email_changed after update of email on auth.users
for each row when (old.email is distinct from new.email) execute function public.sync_profile_email();

alter table public.products enable row level security;
alter table public.profiles enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

revoke all on public.products, public.profiles, public.orders, public.order_items from anon, authenticated;
grant select on public.products to anon, authenticated;
grant select on public.profiles, public.orders, public.order_items to authenticated;
grant update (name,profile_picture,phone,gender,dob,address,city,province) on public.profiles to authenticated;
grant all on public.products, public.profiles, public.orders, public.order_items to service_role;
grant usage,select on all sequences in schema public to service_role;

create policy products_public_read on public.products for select to anon, authenticated using (true);
create policy profiles_owner_read on public.profiles for select to authenticated using ((select auth.uid()) = id);
create policy profiles_owner_update on public.profiles for update to authenticated
using ((select auth.uid()) = id) with check ((select auth.uid()) = id);
create policy orders_owner_read on public.orders for select to authenticated using ((select auth.uid()) = user_id);
create policy order_items_owner_read on public.order_items for select to authenticated
using (exists (select 1 from public.orders o where o.id = order_id and o.user_id = (select auth.uid())));

-- Clients cannot insert orders or change stock. This function owns the entire transaction.
create function public.place_demo_order(p_items jsonb, p_idempotency_key uuid) returns uuid
language plpgsql security definer set search_path = '' as $$
declare
  v_user uuid := auth.uid();
  v_profile public.profiles%rowtype;
  v_product public.products%rowtype;
  v_item record;
  v_items jsonb;
  v_existing public.orders%rowtype;
  v_order uuid;
  v_subtotal numeric(12,2) := 0;
begin
  if v_user is null then raise exception 'Sign in before checking out.' using errcode = '42501'; end if;
  if p_idempotency_key is null then raise exception 'A checkout request ID is required.' using errcode = '22023'; end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' then
    raise exception 'The cart must be an array.' using errcode = '22023';
  end if;
  if jsonb_array_length(p_items) not between 1 and 50 then
    raise exception 'Choose between 1 and 50 products.' using errcode = '22023';
  end if;
  if exists (
    select 1 from jsonb_array_elements(p_items) item
    where jsonb_typeof(item) <> 'object'
       or jsonb_typeof(item->'product_id') is distinct from 'number'
       or jsonb_typeof(item->'quantity') is distinct from 'number'
       or coalesce(item->>'product_id','') !~ '^[1-9][0-9]{0,8}$'
       or coalesce(item->>'quantity','') !~ '^[1-9][0-9]?$'
  ) then raise exception 'Cart products and quantities must be positive integers; maximum quantity is 99.' using errcode = '22023'; end if;
  if (select count(distinct (item->>'product_id')::integer) from jsonb_array_elements(p_items) item) <> jsonb_array_length(p_items) then
    raise exception 'Each product may appear only once in a checkout.' using errcode = '22023';
  end if;
  select jsonb_agg(jsonb_build_object('product_id',(item->>'product_id')::integer,'quantity',(item->>'quantity')::integer)
         order by (item->>'product_id')::integer)
  into v_items from jsonb_array_elements(p_items) item;

  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(v_user::text || ':' || p_idempotency_key::text,0));
  select * into v_existing from public.orders where user_id = v_user and idempotency_key = p_idempotency_key;
  if found then
    if v_existing.request_items <> v_items then raise exception 'This checkout request ID was already used for a different cart.' using errcode = '22023'; end if;
    return v_existing.id;
  end if;

  select * into v_profile from public.profiles where id = v_user;
  if not found or nullif(trim(v_profile.name),'') is null or nullif(trim(v_profile.phone),'') is null or
     nullif(trim(v_profile.address),'') is null or nullif(trim(v_profile.city),'') is null or
     nullif(trim(v_profile.province),'') is null then
    raise exception 'Add your name, phone number and complete delivery address to your profile first.' using errcode = '22023';
  end if;
  -- Stable lock order prevents concurrent carts deadlocking across multiple products.
  for v_item in select (item->>'product_id')::integer as product_id,(item->>'quantity')::integer as quantity
                from jsonb_array_elements(v_items) item order by (item->>'product_id')::integer loop
    select * into v_product from public.products where id = v_item.product_id for update;
    if not found then raise exception 'A selected product no longer exists.' using errcode = '22023'; end if;
    if v_product.stock < v_item.quantity then raise exception 'Insufficient stock for %.',v_product.name using errcode = '22023'; end if;
    v_subtotal := v_subtotal + v_product.price * v_item.quantity;
  end loop;
  insert into public.orders(user_id,idempotency_key,request_items,subtotal,shipping,total,
    delivery_name,delivery_email,delivery_phone,delivery_address,delivery_city,delivery_province)
  values(v_user,p_idempotency_key,v_items,v_subtotal,100,v_subtotal+100,
    v_profile.name,v_profile.email,v_profile.phone,v_profile.address,v_profile.city,v_profile.province)
  returning id into v_order;
  for v_item in select (item->>'product_id')::integer as product_id,(item->>'quantity')::integer as quantity
                from jsonb_array_elements(v_items) item loop
    select * into v_product from public.products where id = v_item.product_id;
    insert into public.order_items(order_id,product_id,product_name,unit_price,quantity,image)
    values(v_order,v_product.id,v_product.name,v_product.price,v_item.quantity,v_product.image);
    update public.products set stock = stock - v_item.quantity where id = v_item.product_id;
  end loop;
  return v_order;
end;
$$;

create function public.sync_product_identity() returns void
language plpgsql security definer set search_path = '' as $$
declare v_max bigint;
begin
  select max(id) into v_max from public.products;
  perform pg_catalog.setval(pg_catalog.pg_get_serial_sequence('public.products','id'), coalesce(v_max,1), v_max is not null);
end;
$$;
revoke all on function public.set_updated_at(), public.protect_profile_identity(), public.handle_new_user(), public.sync_profile_email(),
  public.place_demo_order(jsonb,uuid),public.sync_product_identity() from public, anon, authenticated;
grant execute on function public.place_demo_order(jsonb,uuid) to authenticated;
grant execute on function public.sync_product_identity() to service_role;

